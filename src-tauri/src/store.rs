//! FlipOn's own persistence: settings, account list/state, and per-account OAuth credentials.
//!
//! Credentials are stored as owner-only files (0600 on unix; the per-user app-data folder on Windows).
//! Nothing here is ever sent anywhere except Anthropic, by `api.rs`.

use crate::claude_creds::write_atomic;
use crate::model::{PersistedState, Settings};
use serde::{de::DeserializeOwned, Serialize};
use serde_json::Value;
use std::fs;
use std::path::PathBuf;

#[derive(Clone)]
pub struct Store {
    dir: PathBuf,
}

impl Store {
    pub fn new() -> Self {
        let base = dirs::data_dir().unwrap_or_else(std::env::temp_dir);
        let dir = base.join("FlipOn");
        // the app used to be called Runway: bring its saved accounts along instead of starting empty
        let old = base.join("Runway");
        if !dir.exists() && old.is_dir() {
            if let Err(e) = fs::rename(&old, &dir) {
                eprintln!("[flipon] could not move the old Runway data folder: {e}");
            }
        }
        let store = Self { dir };
        let _ = fs::create_dir_all(store.cred_dir());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let _ = fs::set_permissions(&store.dir, fs::Permissions::from_mode(0o700));
            let _ = fs::set_permissions(store.cred_dir(), fs::Permissions::from_mode(0o700));
        }
        #[cfg(windows)]
        store.lock_down_windows();
        store
    }

    /// Windows has no chmod: drop inherited permissions and grant only the current user access, so the
    /// stored tokens are owner-only like the 0600 files on unix.
    #[cfg(windows)]
    fn lock_down_windows(&self) {
        use std::os::windows::process::CommandExt;
        let Some(user) = std::env::var_os("USERNAME") else { return };
        let grant = format!("{}:(OI)(CI)F", user.to_string_lossy());
        let _ = std::process::Command::new("icacls")
            .arg(&self.dir)
            .args(["/inheritance:r", "/grant:r", &grant])
            .creation_flags(0x0800_0000)
            .output();
    }

    fn cred_dir(&self) -> PathBuf {
        self.dir.join("credentials")
    }

    fn cred_path(&self, id: &str) -> PathBuf {
        // ids are uuids generated by us, but never trust a path component
        let safe: String = id.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-').collect();
        self.cred_dir().join(format!("{safe}.json"))
    }

    fn read<T: DeserializeOwned + Default>(&self, name: &str) -> T {
        fs::read_to_string(self.dir.join(name))
            .ok()
            .and_then(|t| serde_json::from_str(&t).ok())
            .unwrap_or_default()
    }

    fn write<T: Serialize>(&self, name: &str, value: &T) {
        match serde_json::to_vec_pretty(value) {
            Ok(bytes) => {
                if let Err(e) = write_atomic(&self.dir.join(name), &bytes) {
                    eprintln!("[flipon] could not save {name}: {e}");
                }
            }
            Err(e) => eprintln!("[flipon] could not serialize {name}: {e}"),
        }
    }

    pub fn load_settings(&self) -> Settings {
        let mut s: Settings = self.read("settings.json");
        s.sanitize();
        s
    }

    pub fn save_settings(&self, settings: &Settings) {
        self.write("settings.json", settings);
    }

    pub fn load_state(&self) -> PersistedState {
        self.read("state.json")
    }

    pub fn save_state(&self, state: &PersistedState) {
        self.write("state.json", state);
    }

    /// A random id made once per installation. It never leaves this computer: the update check sends
    /// only `day_token`, which changes every day and cannot be traced back to this id.
    pub fn install_id(&self) -> String {
        let path = self.dir.join("install-id");
        if let Ok(text) = fs::read_to_string(&path) {
            let id = text.trim();
            if id.len() >= 16 {
                return id.to_string();
            }
        }
        let id = uuid::Uuid::new_v4().to_string();
        let _ = write_atomic(&path, id.as_bytes());
        id
    }

    /// The `claudeAiOauth` object saved for an account.
    pub fn read_cred(&self, id: &str) -> Option<Value> {
        let text = fs::read_to_string(self.cred_path(id)).ok()?;
        serde_json::from_str(&text).ok()
    }

    pub fn write_cred(&self, id: &str, oauth: &Value) -> Result<(), String> {
        let bytes = serde_json::to_vec(oauth).map_err(|e| e.to_string())?;
        write_atomic(&self.cred_path(id), &bytes).map_err(|e| format!("Could not save credentials: {e}"))
    }

    pub fn delete_cred(&self, id: &str) {
        let _ = fs::remove_file(self.cred_path(id));
    }
}

/// What an update check sends so the server can count this copy once a day: a hash of the install id
/// and today's date (UTC). Tomorrow's token is unrelated to today's, so days cannot be joined.
pub fn day_token(install_id: &str) -> String {
    use sha2::{Digest, Sha256};
    let day = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() / 86_400)
        .unwrap_or(0);
    let digest = Sha256::digest(format!("flipon-active|{install_id}|{day}").as_bytes());
    digest.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod day_token_tests {
    use super::day_token;

    #[test]
    fn token_is_hex_and_stable_within_a_day() {
        let a = day_token("install-one-aaaaaaaa");
        assert_eq!(a.len(), 64);
        assert!(a.chars().all(|c| c.is_ascii_hexdigit()));
        assert_eq!(a, day_token("install-one-aaaaaaaa"));
        assert_ne!(a, day_token("install-two-bbbbbbbb"));
    }
}
